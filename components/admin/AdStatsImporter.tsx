'use client';

import { useCallback, useEffect, useState } from 'react';
import { supabase } from '@/lib/supabase';
import { G } from '@/lib/theme';
import { useTheme } from '../ThemeProvider';
import { SetupNote } from './ToolShared';

type Stat = { date: string; impressions: number; profit: number; cpm: number };

const SETUP_SQL = `create table ad_stats (
  id bigint generated by default as identity primary key,
  source text not null default 'monetag',
  date date not null,
  impressions integer default 0,
  profit numeric default 0,
  cpm numeric default 0,
  uploaded_at timestamptz default now(),
  unique (source, date)
);`;

// Monetag's "Export to CSV" (Statistics tab) gives "Date;Impressions;Profit;CPM"
// with a totals row at the end that has no date; we skip it.
function parseMonetagCSV(csv: string): Stat[] {
  const lines = csv.trim().split(/\r?\n/).filter(Boolean);
  if (lines.length < 2) return [];
  const delim = lines[0].includes(';') ? ';' : ',';
  return lines
    .slice(1)
    .map((line) => {
      const [date, impressions, profit, cpm] = line.split(delim);
      return { date: (date || '').trim(), impressions: Number(impressions) || 0, profit: Number(profit) || 0, cpm: Number(cpm) || 0 };
    })
    .filter((r) => /^\d{4}-\d{2}-\d{2}$/.test(r.date));
}

export default function AdStatsImporter() {
  const { card, border, text, muted } = useTheme();
  const [stats, setStats] = useState<Stat[]>([]);
  const [available, setAvailable] = useState(true);
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState('');

  const load = useCallback(async () => {
    try {
      const { data, error } = await supabase.from('ad_stats').select('*').order('date', { ascending: true });
      if (error) setAvailable(false);
      else setStats((data || []) as Stat[]);
    } catch {
      setAvailable(false);
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const onFile = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const input = e.target;
    const file = input.files?.[0];
    if (!file) return;
    setBusy(true);
    setMessage('');
    try {
      const rows = parseMonetagCSV(await file.text());
      if (rows.length === 0) {
        setMessage('No valid rows found. Check this is a Monetag CSV export.');
      } else {
        const records = rows.map((r) => ({ source: 'monetag', ...r }));
        const { error } = await supabase.from('ad_stats').upsert(records, { onConflict: 'source,date' });
        if (error) setMessage('Error: ' + error.message);
        else {
          setMessage(`Imported ${records.length} row${records.length === 1 ? '' : 's'} ✅`);
          load();
        }
      }
    } catch {
      setMessage('Connection error. Try again.');
    }
    setBusy(false);
    input.value = '';
  };

  const totalProfit = stats.reduce((s, r) => s + Number(r.profit), 0);
  const totalImpressions = stats.reduce((s, r) => s + Number(r.impressions), 0);
  const avgCpm = stats.length ? stats.reduce((s, r) => s + Number(r.cpm), 0) / stats.length : 0;
  const maxProfit = Math.max(...stats.map((r) => Number(r.profit)), 0.01);
  const recent = stats.slice(-30);

  return (
    <div>
      <div style={{ background: card, border: `1px solid ${border}`, borderRadius: 10, padding: 16, marginBottom: 16 }}>
        <div style={{ fontSize: 14, fontWeight: 700, color: text, marginBottom: 8 }}>📊 Google Analytics Snapshot</div>
        <div style={{ fontSize: 13, color: muted, lineHeight: 1.7 }}>
          Not wired up yet. Showing live GA4 numbers here needs a Google Cloud service account with Viewer access to your GA4 property and a small server-side function to keep that credential off the browser.
        </div>
      </div>

      <div style={{ background: card, border: `1px solid ${border}`, borderRadius: 10, padding: 16 }}>
        <div style={{ fontSize: 14, fontWeight: 700, color: text, marginBottom: 8 }}>💰 Ad Performance (Monetag)</div>
        <div style={{ fontSize: 12, color: muted, lineHeight: 1.6, marginBottom: 12 }}>
          Monetag has no public reporting API on this account tier. Export your CSV from Monetag (Statistics → Export to CSV) and upload it here. Re-uploading just refreshes matching dates, so it is safe to repeat.
        </div>
        {!available && <SetupNote table="ad_stats" sql={SETUP_SQL} />}
        <div style={{ marginBottom: 16 }}>
          <input type="file" accept=".csv" onChange={onFile} disabled={busy || !available} />
          {busy && <div style={{ fontSize: 12, color: muted, marginTop: 6 }}>Importing…</div>}
          {message && <div style={{ fontSize: 12, color: message.startsWith('Error') || message.startsWith('No valid') ? G.red : G.green, marginTop: 6 }}>{message}</div>}
        </div>

        {available && stats.length > 0 && (
          <div>
            <div style={{ display: 'flex', gap: 24, marginBottom: 20, flexWrap: 'wrap' }}>
              {[['Total Profit', `$${totalProfit.toFixed(2)}`], ['Total Impressions', totalImpressions.toLocaleString()], ['Avg CPM', `$${avgCpm.toFixed(2)}`]].map(([l, v]) => (
                <div key={l}>
                  <div style={{ fontSize: 11, color: muted, textTransform: 'uppercase' }}>{l}</div>
                  <div style={{ fontSize: 22, fontWeight: 700, color: text }}>{v}</div>
                </div>
              ))}
            </div>
            <div style={{ display: 'flex', alignItems: 'flex-end', gap: 3, height: 140, borderBottom: `1px solid ${border}`, paddingBottom: 4, overflowX: 'auto' }}>
              {recent.map((r) => (
                <div key={r.date} title={`${r.date}: $${Number(r.profit).toFixed(3)}`} style={{ flex: '0 0 auto', width: 10, height: `${Math.max(4, (Number(r.profit) / maxProfit) * 130)}px`, background: '#6366f1', borderRadius: '2px 2px 0 0' }} />
              ))}
            </div>
            <div style={{ fontSize: 11, color: muted, marginTop: 6 }}>Daily profit, last {recent.length} uploaded days. Hover a bar for the exact date and amount.</div>
          </div>
        )}
        {available && stats.length === 0 && <div style={{ fontSize: 12, color: muted }}>No data yet. Upload your first Monetag CSV export above.</div>}
      </div>
    </div>
  );
}
